#!/bin/bash
# =====================================================================================
#  Student Timer Clock - signed release build
#
#   1. pins the code-signing certificate into the source (src/Security/SignerPin.cs)
#   2. publishes the app with integrity enforcement ON (-p:IntegrityEnforced=true)
#        installer payload : self-contained single-file exe (all code inside one signed file)
#        portable          : framework-dependent single-file exe
#   3. Authenticode-signs the executables (SHA-256, RFC 3161 timestamp)
#   4. writes the signed integrity manifest (integrity.json + integrity.sig) next to each exe
#   5. builds the NSIS installer; makensis signs the installer and the uninstaller
#   6. verifies every signature, writes SHA256SUMS.txt (+ CMS signature)
#   7. generates the PDF "Certificate of Integrity"
#
#  Requirements: .NET 8 SDK, osslsigncode, openssl, makensis (NSIS >= 3.08), python3 + reportlab
#  To sign with a CA-issued certificate: SIGN_PFX=/path/cert.pfx SIGN_PASSWORD_FILE=/path/pw.txt ./build-release.sh
# =====================================================================================
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VERSION="$(grep -oP '(?<=public const string Version = ")[^"]+' "$ROOT/src/HelpForm.cs")"
NAME="StudentTimerClock version $VERSION"
WORK="${WORK:-$HOME/.cache/stc-release}"
OUT="$ROOT/release"
PFX="${SIGN_PFX:-$ROOT/signing/private/codesign.pfx}"
PWF="${SIGN_PASSWORD_FILE:-$ROOT/signing/private/key-password.txt}"
export DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1
export STC_PW="$(cat "$PWF")"

echo "== Student Timer Clock $VERSION - signed release build"
rm -rf "$WORK"; mkdir -p "$WORK"/{pub-sc,pub-fd,stage-installer,stage-portable,certs}

# ---- 1. certificate + pin -------------------------------------------------------------
openssl pkcs12 -in "$PFX" -passin env:STC_PW -clcerts -nokeys -out "$WORK/certs/signer.pem" 2>/dev/null
openssl pkcs12 -in "$PFX" -passin env:STC_PW -nocerts -out "$WORK/certs/signer.key" -passout env:STC_PW 2>/dev/null
PIN="$(openssl x509 -in "$WORK/certs/signer.pem" -outform DER | sha256sum | cut -d' ' -f1 | tr a-f A-F)"
SUBJ="$(openssl x509 -in "$WORK/certs/signer.pem" -noout -subject -nameopt RFC2253 | sed 's/^subject=//')"
cat > "$ROOT/src/Security/SignerPin.cs" <<EOF
// <auto-generated> Written by scripts/build-release.sh - do not edit by hand. </auto-generated>
namespace StudentTimerClock.Security;

/// <summary>SHA-256 fingerprint of the code-signing certificate that release builds must be signed with.</summary>
public static class SignerPin
{
    public const string Sha256 = "$PIN";
    public const string Subject = "${SUBJ//\"/\\\"}";
}
EOF
echo "   signer : $SUBJ"
echo "   pin    : $PIN"

# ---- 2. publish -----------------------------------------------------------------------
cd "$ROOT/src"
rm -rf bin obj
dotnet publish -c Release -r win-x64 --self-contained true  -p:PublishSingleFile=true -p:EnableCompressionInSingleFile=true \
    -p:DebugType=none -p:IntegrityEnforced=true -o "$WORK/pub-sc" 2>&1 | grep -E " error |Warn|->" || true
rm -rf bin obj
dotnet publish -c Release -r win-x64 --self-contained false -p:PublishSingleFile=true \
    -p:DebugType=none -p:IntegrityEnforced=true -o "$WORK/pub-fd" 2>&1 | grep -E " error |Warn|->" || true
rm -rf bin obj
test -f "$WORK/pub-sc/StudentTimerClock.exe" && test -f "$WORK/pub-fd/StudentTimerClock.exe"
# WPF-only native helpers are not used by this WinForms app -> not shipped (smaller attack surface)
cp "$WORK/pub-sc/StudentTimerClock.exe" "$WORK/stage-installer/"
cp "$WORK/pub-fd/StudentTimerClock.exe" "$WORK/stage-portable/"

# ---- 3. sign --------------------------------------------------------------------------
"$ROOT/scripts/sign-file.sh" "$WORK/stage-installer/StudentTimerClock.exe"
"$ROOT/scripts/sign-file.sh" "$WORK/stage-portable/StudentTimerClock.exe"

# ---- 4. signed manifests --------------------------------------------------------------
echo "   manifest (installer payload):"
python3 "$ROOT/scripts/make_manifest.py" "$WORK/stage-installer" "$VERSION" "$WORK/certs/signer.key" "$PWF"
echo "   manifest (portable):"
python3 "$ROOT/scripts/make_manifest.py" "$WORK/stage-portable" "$VERSION" "$WORK/certs/signer.key" "$PWF"

# ---- 5. installer (makensis signs installer + uninstaller via !finalize) ---------------
cd "$ROOT/installer"
makensis -V2 -DPAYLOAD="$WORK/stage-installer" -DOUTFILE="$WORK/$NAME.exe" -DSIGNCMD="$ROOT/scripts/sign-file.sh" StudentTimerClock.nsi

# ---- portable zip ---------------------------------------------------------------------
cat > "$WORK/stage-portable/README.txt" <<EOF
Student Timer Clock $VERSION - portable edition
Requires the Microsoft .NET 8 Desktop Runtime (x64): https://dotnet.microsoft.com/download/dotnet/8.0

Keep these files together in one folder:
  StudentTimerClock.exe   digitally signed program
  integrity.json          signed list of SHA-256 hashes (checked by the program at start and every 5 minutes)
  integrity.sig           signature of integrity.json
The program refuses to run if any of them is missing or modified.
Put an empty file named portable.txt next to the exe to keep your data in this folder instead of %APPDATA%.
EOF
rm -f "$WORK/$NAME (portable, needs NET 8).zip"
(cd "$WORK/stage-portable" && zip -q -X "$WORK/$NAME (portable, needs NET 8).zip" StudentTimerClock.exe integrity.json integrity.sig README.txt)

# ---- 6. verify + checksums ------------------------------------------------------------
CHAIN="$ROOT/signing/root-ca.crt"; [ -n "${SIGN_CA_FILE:-}" ] && CHAIN="$SIGN_CA_FILE"
for pair in "installed-app:$WORK/stage-installer/StudentTimerClock.exe" "portable-app:$WORK/stage-portable/StudentTimerClock.exe" "installer:$WORK/$NAME.exe"; do
  role="${pair%%:*}"; f="${pair#*:}"
  osslsigncode verify -CAfile "$CHAIN" -in "$f" > "$WORK/verify-$role.txt" 2>&1 \
    && echo "   signature OK : $role ($(basename "$f"))" || { echo "SIGNATURE VERIFICATION FAILED: $f"; cat "$WORK/verify-$role.txt"; exit 1; }
done
mkdir -p "$OUT"; rm -f "$OUT"/*
cp "$WORK/$NAME.exe" "$WORK/$NAME (portable, needs NET 8).zip" "$OUT/"
cp "$ROOT/signing/Student Timer Clock Root CA.cer" "$ROOT/signing/Student Timer Clock Code Signing.cer" "$OUT/"
cp "$WORK/stage-installer/integrity.json" "$OUT/integrity-manifest (installed app).json"
chmod 644 "$OUT"/*
(cd "$OUT" && sha256sum -- "$NAME.exe" "$NAME (portable, needs NET 8).zip" "Student Timer Clock Root CA.cer" "Student Timer Clock Code Signing.cer" > SHA256SUMS.txt)
openssl cms -sign -binary -md sha256 -in "$OUT/SHA256SUMS.txt" -signer "$WORK/certs/signer.pem" -inkey "$WORK/certs/signer.key" -passin env:STC_PW \
    -certfile "$ROOT/signing/root-ca.crt" -outform DER -out "$OUT/SHA256SUMS.txt.p7s"
openssl cms -verify -binary -inform DER -in "$OUT/SHA256SUMS.txt.p7s" -content "$OUT/SHA256SUMS.txt" -CAfile "$ROOT/signing/root-ca.crt" -purpose any -out /dev/null 2>/dev/null \
    && echo "   SHA256SUMS signature OK"

# ---- 7. certificate of integrity (PDF) ------------------------------------------------
python3 "$ROOT/scripts/make_integrity_record.py" --root "$ROOT" --work "$WORK" --version "$VERSION" --pin "$PIN" \
    --out "$OUT/$NAME - Certificate of Integrity.pdf"
openssl cms -sign -binary -md sha256 -in "$OUT/$NAME - Certificate of Integrity.pdf" -signer "$WORK/certs/signer.pem" -inkey "$WORK/certs/signer.key" \
    -passin env:STC_PW -certfile "$ROOT/signing/root-ca.crt" -outform DER -out "$OUT/$NAME - Certificate of Integrity.pdf.p7s"
sed -i '/Certificate of Integrity.pdf$/d' "$OUT/SHA256SUMS.txt"
(cd "$OUT" && sha256sum -- "$NAME - Certificate of Integrity.pdf" >> SHA256SUMS.txt)
openssl cms -sign -binary -md sha256 -in "$OUT/SHA256SUMS.txt" -signer "$WORK/certs/signer.pem" -inkey "$WORK/certs/signer.key" -passin env:STC_PW \
    -certfile "$ROOT/signing/root-ca.crt" -outform DER -out "$OUT/SHA256SUMS.txt.p7s"
echo "== done"; ls -la "$OUT"
